# isalpha() - True si todos los caracteres pertenecen al alfabeto
palabra = "Python"
print(palabra.isalpha())

# isdigit() - True si todos los caracteres son digitos
numero = "12345"
print(numero.isdigit())

# isupper() - True si todos los caracteres estan en mayusculas
mayus = "HOLA"
print(mayus.isupper())
