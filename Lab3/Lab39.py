# capitalize() - convierte la primera letra en mayuscula
texto = "hola mundo desde python"
print(texto.capitalize())

# count() - devuelve el numero de veces que aparece un valor
frase = "el sol sale y el sol brilla"
print(frase.count("el"))

# find() - busca un valor y retorna su posicion
cadena = "Hello, World!"
print(cadena.find("World"))
